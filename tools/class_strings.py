#!/usr/bin/env python3
"""Report namespace-qualified class-name strings, the functions that reference them, and the
vtables (data words pointing at those functions) that contain those functions. Evidence for
naming game classes by hand; it renames nothing. Usage: class_strings.py DOL SYMBOLS OUT_MD"""
import collections, re, struct, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from fuzzy_match import Side

def main(dolp, symp, out):
    D = Side(dolp, symp)
    name = {f['addr']: f['name'] for f in D.fns}
    holders = collections.defaultdict(set)
    for a, sz, o in D.secs:
        if a < 0x80653FA0: continue
        for i in range(0, sz - 3, 4):
            w = struct.unpack('>I', D.dol[o + i:o + i + 4])[0]
            if w in D.at: holders[w].add(a + i)
    labels = sorted((s['addr'], s['name']) for s in D.syms if not s['func'] and s['sec'] == '.data')
    def label_of(x):
        lo, hi = 0, len(labels)
        while lo < hi:
            mid = (lo + hi) // 2
            if labels[mid][0] <= x: lo = mid + 1
            else: hi = mid
        return labels[lo - 1][1] if lo else '?'
    rows = []
    # strings reached through data tables: find each string's address and data words pointing at it
    blob = {a: D.dol[o:o + sz] for a, sz, o in D.secs if a >= 0x80653FA0 and o}
    words_at = collections.defaultdict(list)
    for a, b in blob.items():
        for i in range(0, len(b) - 3, 4): words_at[struct.unpack('>I', b[i:i + 4])[0]].append(a + i)
    for a, b in blob.items():
        for m in re.finditer(rb'[A-Za-z][A-Za-z0-9]*(?:::[A-Za-z_][A-Za-z0-9_]*)+[ -~]*\0', b):
            st = m.group()[:-1].decode(); sa = a + m.start()
            refs = words_at.get(sa, [])
            if st not in D.strfn and refs:
                rows.append(f'| `{st}` | (data ref) | {", ".join(sorted({label_of(r) for r in refs}))} |')
    for s, fs in sorted(D.strfn.items()):
        if not re.search(r'[A-Z][A-Za-z0-9]*::[A-Za-z_]', s): continue
        for f in sorted(fs):
            tabs = sorted({label_of(h) for h in holders.get(f, ())})
            rows.append(f'| `{s}` | `{name[f]}` 0x{f:08X} | {", ".join(tabs) or "-"} |')
    open(out, 'w').write('# Class-name strings in main.dol\n\nGenerated by `tools/class_strings.py`. '
        'Evidence only: a string may name the class itself, a parent, or just appear in a log message.\n\n'
        '| String | Referencing function | Data objects holding a pointer to it (vtable candidates) |\n|---|---|---|\n'
        + '\n'.join(rows) + '\n')
    print(f'{len(rows)} rows -> {out}')

if __name__ == '__main__': main(*sys.argv[1:])
