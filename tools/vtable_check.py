#!/usr/bin/env python3
"""Check vtables against unit boundaries. A vtable-shaped object ({0 or type-info, 0, fn, fn, ...})
in a unit's .data should have most of its slot functions in that unit's .text; slots elsewhere are
either inherited (base class) or a sign the boundary is wrong. Reports per-vtable placement.
Usage: vtable_check.py DOL SYMBOLS SPLITS OUT_MD"""
import bisect, collections, struct, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from sig_match import symbols, dol_sections, read
from apply_ogws import parse_splits
d, ds = dol_sections(sys.argv[1]); S = symbols(sys.argv[2]); sp = parse_splits(sys.argv[3])
fn = {s['addr'] for s in S if s['func']}
text = sorted((s, e, u) for u, v in sp.items() for (sec, s, e) in v if sec == '.text'); ts = [t[0] for t in text]
def unit_of(a):
    i = bisect.bisect_right(ts, a) - 1
    return text[i][2] if i >= 0 and a < text[i][1] else None
data = sorted((s, e, u) for u, v in sp.items() for (sec, s, e) in v if sec == '.data'); dst = [x[0] for x in data]
def dunit(a):
    i = bisect.bisect_right(dst, a) - 1
    return data[i][2] if i >= 0 and a < data[i][1] else None
rows = []; stats = collections.Counter()
for s in S:
    if s['sec'] != '.data' or s['size'] < 12: continue
    w = read(d, ds, s['addr'], s['size']); W = [struct.unpack('>I', w[i:i + 4])[0] for i in range(0, len(w) - 3, 4)]
    if len(W) < 3 or W[1] != 0 or not all(x in fn or x == 0 for x in W[2:]) or sum(x in fn for x in W[2:]) < 2: continue
    owner = dunit(s['addr'])
    if not owner: stats['vtable in unowned data'] += 1; continue
    slots = [x for x in W[2:] if x in fn]
    places = collections.Counter(unit_of(x) for x in slots)
    top, n = places.most_common(1)[0]
    if top == owner: stats['majority of slots in owner unit'] += 1
    else:
        stats['majority elsewhere'] += 1
        rows.append(f"| `{s['name']}` 0x{s['addr']:08X} | `{owner}` | `{top}` ({n}/{len(slots)}) |")
open(sys.argv[4], 'w').write('# Vtables whose methods sit mostly outside the owning unit\n\nGenerated by `tools/vtable_check.py`. '
    'Inherited slots are expected elsewhere; a vtable whose own methods are elsewhere suggests a wrong boundary '
    '(or a data range assigned to the wrong unit).\n\n| Vtable | Data owner | Most slots in |\n|---|---|---|\n' + '\n'.join(rows) + '\n')
print(dict(stats))
