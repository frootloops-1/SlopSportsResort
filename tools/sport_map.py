#!/usr/bin/env python3
"""Attribute code to sports from the resource-name strings each function references.

A string votes for a sport when it contains WS2_<code>_ or starts with <code>_ (e.g. glf_avatar).
Each split unit (and each run of auto code between splits) gets the sport with most votes.
Writes docs/sport_map.md. Usage: sport_map.py DOL SYMBOLS SPLITS OUT_MD"""
import collections, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from fuzzy_match import Side
from apply_ogws import parse_splits

SPORTS = {'swf': 'Swordplay', 'wkb': 'Wakeboarding', 'fld': 'Frisbee Dog', 'arc': 'Archery', 'bsk': 'Basketball',
          'png': 'Table Tennis', 'glf': 'Golf', 'bwg': 'Bowling', 'can': 'Canoeing', 'bic': 'Cycling',
          'pln': 'Air Sports', 'jsk': 'Power Cruising', 'dgl': 'Frisbee Golf', 'omk': 'Island Flyover / Air Sports extras'}
PAT = re.compile(r'(?:WS2_|(?:^|[/_ ]))(' + '|'.join(SPORTS) + r')_')

def main(dolp, symp, splp, out):
    D = Side(dolp, symp)
    votes = {}
    for a, ss in D.strs.items():
        c = collections.Counter(m.group(1) for s in ss for m in PAT.finditer(s))
        if c: votes[a] = c
    sp = parse_splits(splp)
    units = sorted((s, e, u) for u, v in sp.items() for (sec, s, e) in v if sec == '.text')
    per_unit = collections.defaultdict(collections.Counter)
    for a, c in votes.items():
        u = next((u for s, e, u in units if s <= a < e), None) or f'auto@{a & ~0xFFFF:08X}'
        per_unit[u].update(c)
    rows = []
    for u, c in per_unit.items():
        (top, n), *rest = c.most_common()
        share = n / sum(c.values())
        s = next((s for s0, e0, uu in units if uu == u for s in [s0]), None)
        rows.append((s or int(u.split('@')[1], 16), u, top, n, share, dict(c.most_common(3))))
    rows.sort()
    by_sport = collections.defaultdict(list)
    for s, u, top, n, share, c in rows:
        if share >= 0.6: by_sport[top].append((s, u, n))
    lines = ['# Code attributed to sports', '',
             'Generated by `tools/sport_map.py` from resource-name strings (`WS2_<code>_...`, `<code>_...`) referenced '
             'by each function. A unit is listed under a sport when >= 60% of its string votes agree. Evidence only.', '',
             '| Sport | Code | Units | Address span | Units (first 6) |', '|---|---|---|---|---|']
    for code, lst in sorted(by_sport.items(), key=lambda kv: kv[1][0][0]):
        lo, hi = min(x[0] for x in lst), max(x[0] for x in lst)
        lines.append(f"| {SPORTS[code]} | `{code}` | {len(lst)} | 0x{lo:08X}-0x{hi:08X} | " + ', '.join(f'`{x[1]}`' for x in lst[:6]) + ' |')
    lines += ['', '## Mixed units (no sport >= 60%)', ''] + [f'- `{u}` 0x{s:08X}: {c}' for s, u, top, n, share, c in rows if share < 0.6]
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(votes)} functions reference sport strings; {sum(len(v) for v in by_sport.values())} units attributed')
    for code, lst in sorted(by_sport.items(), key=lambda kv: kv[1][0][0]):
        print(f'  {code} {SPORTS[code]:<16} {len(lst):3} units  0x{min(x[0] for x in lst):08X}-0x{max(x[0] for x in lst):08X}')

if __name__ == '__main__': main(*sys.argv[1:])
